const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { JSDOM, VirtualConsole } = require('jsdom');
const root = path.resolve(__dirname, '..');
const sent = [];
const errors = [];
const console = new VirtualConsole();
console.on('jsdomError', (error) => errors.push(error.message));
const html = fs.readFileSync(path.join(root, 'media', 'chat.html'), 'utf8').replace(/<script[\s\S]*?<\/script>/g, '').replace(/<link[^>]+>/g, '');
let local;
const dom = new JSDOM(html, { runScripts: 'outside-only', pretendToBeVisual: true, virtualConsole: console });
const { window } = dom;
window.acquireVsCodeApi = () => ({ postMessage: (message) => sent.push(message), getState: () => local, setState: (value) => { local = value; } });
window.eval(fs.readFileSync(path.join(root, 'media', 'chat.js'), 'utf8'));
const element = (id) => window.document.getElementById(id);
const receive = (message) => window.dispatchEvent(new window.MessageEvent('message', { data: message }));
const last = () => sent.at(-1);
const view = () => element('agent').dataset.view;
const values = { baseUrl: 'http://localhost:8000/v1', model: 'test-model', approvalMode: 'ask', contextWindow: 128000, maxOutputTokens: 8192, autoContext: true, allowedCommands: '', systemPromptExtra: '', hasKey: true };

assert.equal(last().type, 'ready');
receive({ type: 'state', configured: true, sessionId: 'alpha', model: 'test-model', busy: false, mode: 'ask' });
receive({ type: 'history', sessionId: 'alpha', messages: [], draft: '' });
assert.equal(element('welcome').hidden, false);
assert.equal(element('historyList').closest('#scrollArea'), null);
assert.equal(window.document.querySelectorAll('[id="toggleSettings"]').length, 1);
element('messageInput').value = 'keep this draft';
element('scrollArea').scrollTop = 123;
element('toggleSettings').click();
assert.equal(view(), 'settings');
assert.equal(element('composerArea').inert, true);
receive({ type: 'settingsData', values });
assert.equal(element('apiKey').value, '');
element('model').value = 'changed-model';
element('settingsForm').dispatchEvent(new window.Event('input', { bubbles: true }));
element('closeSettings').click();
assert.equal(element('scrollArea').scrollTop, 123);
element('toggleSettings').click();
assert.equal(element('model').value, 'changed-model');
element('testConnection').click();
assert.equal(last().type, 'testConnection');
assert.equal(last().values.model, 'changed-model');
const testRequest = last().requestId;
receive({ type: 'settingsResult', action: 'testConnection', requestId: testRequest + 10, ok: false, message: 'outdated result' });
assert.notEqual(element('formResult').textContent, 'outdated result');
receive({ type: 'settingsResult', action: 'testConnection', requestId: testRequest, ok: false, message: 'Connection failed' });
assert.equal(element('formResult').classList.contains('error'), true);
assert.equal(element('testConnection').disabled, false);
element('settingsForm').dispatchEvent(new window.Event('submit', { cancelable: true }));
assert.equal(last().type, 'saveSettings');
const saveRequest = last().requestId;
receive({ type: 'settingsResult', action: 'saveSettings', requestId: saveRequest, ok: true, message: 'saved', values: { ...values, model: 'changed-model' } });
assert.equal(view(), 'chat');
assert.equal(element('messageInput').value, 'keep this draft');
element('sendMessage').click();
assert.equal(last().type, 'send');
receive({ type: 'user', text: 'keep this draft' });
receive({ type: 'state', busy: true });
receive({ type: 'assistantStart', id: 'answer' });
receive({ type: 'textDelta', text: '**Hello**\n\n<script>bad()</script>\n\n```js\n<img src=x onerror=bad()>\n```\n\n| A | B |\n| -- | -- |\n| 1 | 2 |' });
receive({ type: 'assistantEnd', meta: 'test-model' });
assert.equal(element('messages').querySelector('strong').textContent, 'Hello');
assert.equal(element('messages').querySelectorAll('script,img').length, 0);
assert.equal(element('messages').querySelector('table td').textContent, '1');
element('messageInput').value = 'followup draft';
receive({ type: 'user', text: 'replayed prompt', replay: true });
assert.equal(element('messageInput').value, 'followup draft');
receive({ type: 'assistantStart', id: 'approve-answer' });
receive({ type: 'approval', request: { id: 'approval-1', kind: 'edit', title: '修改 a.txt', relPath: 'a.txt', canDiff: true } });
const actions = element('messages').querySelectorAll('.approval button');
actions[0].click();
assert.equal(last().type, 'openDiff');
actions[1].click();
assert.equal(last().type, 'approvalResponse');
assert.equal(last().decision, 'allow');
receive({ type: 'approvalDone', id: 'approval-1', decision: 'allow' });
assert.equal(element('messages').querySelectorAll('.approval button').length, 0);
element('sendMessage').click();
assert.equal(last().type, 'stop');
receive({ type: 'state', busy: false });
element('toggleHistory').click();
receive({ type: 'sessions', activeId: 'alpha', sessions: [{ id: 'alpha', title: 'first', updatedAt: 1000 }, { id: 'beta', title: 'second', updatedAt: 2000 }] });
element('historyList').querySelectorAll('button')[1].click();
assert.equal(last().type, 'selectSession');
assert.equal(last().draft, 'followup draft');
receive({ type: 'state', sessionId: 'beta', configured: true, busy: false });
receive({ type: 'history', sessionId: 'beta', messages: [{ role: 'user', content: 'second prompt' }], draft: 'beta draft' });
assert.equal(view(), 'chat');
assert.equal(element('messageInput').value, 'beta draft');
assert.equal(element('messages').querySelectorAll('.user').length, 1);
element('newChat').click();
assert.equal(last().type, 'newSession');
receive({ type: 'sessionSwitchFailed', message: 'Please choose again' });
assert.equal(element('sendMessage').disabled, false);
receive({ type: 'history', sessionId: 'gamma', messages: [], draft: '' });
assert.equal(element('welcome').hidden, false);
assert.equal(element('messageInput').value, '');
assert.deepEqual(errors, []);
window.close();
process.stdout.write('webview tests passed: settings/drafts/history/streaming/Markdown safety/approval/session switching\n');
